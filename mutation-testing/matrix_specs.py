#!/usr/bin/env python3
"""Write the Proctor specification set for each REST combination in
examples/matrix/ (proctor.yaml, manifest.yaml, specs/users.yaml and the local
binding). The contract is gopamin's users API, checked the same way for every
combination; what differs is the ID format of a user that doesn't exist,
whether the API needs a token, and whether a PostgreSQL check is possible.

    python3 -I mutation-testing/matrix_specs.py

Rerun it after changing the template; the generated files are reviewed like
any other specification.
"""

import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATRIX = os.path.join(REPO, "examples", "matrix")

REST = {
    "m01-echo-mysql": {"prefix": "M01", "port": 18101, "unknown": "2000000000", "store": "MySQL"},
    "m02-gin-mongodb": {"prefix": "M02", "port": 18102, "unknown": "ffffffffffffffffffffffff", "store": "MongoDB", "content_type": "application/json; charset=utf-8"},
    "m03-gorilla-sqlite": {"prefix": "M03", "port": 18103, "unknown": "2000000000", "store": "SQLite"},
    "m04-httprouter-mariadb": {"prefix": "M04", "port": 18104, "unknown": "2000000000", "store": "MariaDB"},
    "m06-chi-cassandra-rabbitmq": {"prefix": "M06", "port": 18106, "unknown": "00000000-0000-4000-8000-000000000000", "store": "Cassandra", "jwt": True},
    "m07-echo-postgres-redis": {"prefix": "M07", "port": 18107, "unknown": "2000000000", "store": "PostgreSQL", "jwt": True, "postgres": True},
    "m08-http-dynamodb-kafka": {"prefix": "M08", "port": 18108, "unknown": "00000000-0000-4000-8000-000000000000", "store": "DynamoDB"},
}

HEADER = """# Generated by mutation-testing/matrix_specs.py for the gopamin combination
# matrix (testing phase, 2026-11-14). The same users-API contract for every
# combination; only the parts that differ between combinations vary.
"""


def stored(c, sid, id_ref, name):
    """A state check: a database check when PostgreSQL is available, or a read through the API."""
    if c.get("postgres"):
        return f"""      - id: {sid}
        verify:
          postgres:
            connection: app
            query: SELECT name FROM users WHERE id = $1
            args: ["${{{id_ref}}}"]
            expect:
              rows: 1
              first_row: {{ name: "{name}" }}
"""
    return f"""      - id: {sid}
        request: {{ method: GET, path: "/api/v1/users/${{{id_ref}}}", identity: {c['who']} }}
        expect:
          status: 200
          json:
            $: {{ message: Fetched user successfully, data: {{ id: "${{{id_ref}}}", name: "{name}" }} }}
"""


def create(c, sid, name, save=None):
    s = f"""      - id: {sid}
        request: {{ method: POST, path: /api/v1/users, identity: {c['who']}, body: {{ name: "{name}" }} }}
        expect: {{ status: 201 }}
"""
    return s + (f"        save: {{ {save}: $.data }}\n" if save else "")


def spec(c):
    p, who = c["prefix"], c["who"]
    read = lambda id_ref, name: f"""      - id: read
        request: {{ method: GET, path: "/api/v1/users/${{{id_ref}}}", identity: {who} }}
        expect:
          status: 200
          headers:
            Content-Type: {c.get("content_type", "application/json")}
          json:
            $: {{ message: Fetched user successfully, data: {{ id: "${{{id_ref}}}", name: "{name}" }} }}
"""
    s = HEADER + "version: 1\nsuite: users\nscenarios:\n"
    s += f"""  - id: {p}-001
    name: A created user can be read back
    steps:
      - id: create
        request: {{ method: POST, path: /api/v1/users, identity: {who}, body: {{ name: "Ada ${{run.id}}" }} }}
        expect:
          status: 201
          keys:
            $: [message, data]
          json:
            $.message: Created user successfully
        save: {{ user_id: $.data }}
"""
    if c.get("postgres"):
        s += """      - id: stored-once
        verify:
          postgres:
            connection: app
            query: SELECT count(*) AS n FROM users WHERE name = $1
            args: ["Ada ${run.id}"]
            expect:
              first_row: { n: 1 }
"""
    s += read("user_id", "Ada ${run.id}")
    s += f"""
  - id: {p}-002
    name: A user can't be created with an empty name
    steps:
      - id: create-empty
        request: {{ method: POST, path: /api/v1/users, identity: {who}, body: {{ name: "" }} }}
"""
    if c.get("postgres"):
        s += """        expect:
          status: 422
          json:
            $: { message: name is required, error: Validation failed }
      - id: nothing-stored
        verify:
          postgres:
            connection: app
            query: SELECT count(*) AS n FROM users WHERE name = ''
            expect:
              first_row: { n: 0 }
"""
    else:
        s += f"""        no_state_check: Proctor has no {c['store']} adapter, and a refused create returns no ID to read back
        expect:
          status: 422
          json:
            $: {{ message: name is required, error: Validation failed }}
"""
    s += f"""
  - id: {p}-003
    name: Reading a user that doesn't exist returns 404
    steps:
      - id: read-unknown
        request: {{ method: GET, path: /api/v1/users/{c['unknown']}, identity: {who} }}
        expect:
          status: 404
          json:
            $: {{ error: Not found }}

  - id: {p}-004
    name: A rename is returned and persisted
    setup:
{create(c, 'create', 'Ada ${run.id}', 'user_id')}    steps:
      - id: rename
        request: {{ method: PUT, path: "/api/v1/users/${{user_id}}", identity: {who}, body: {{ name: "Grace ${{run.id}}" }} }}
        expect:
          status: 200
          json:
            $: {{ message: User updated successfully, data: {{ id: "${{user_id}}", name: "Grace ${{run.id}}" }} }}
{stored(c, 'stored', 'user_id', 'Grace ${run.id}')}{read('user_id', 'Grace ${run.id}')}
  - id: {p}-005
    name: A deleted user is gone
    setup:
{create(c, 'create', 'Ada ${run.id}', 'user_id')}    steps:
      - id: delete
        request: {{ method: DELETE, path: "/api/v1/users/${{user_id}}", identity: {who} }}
        expect:
          status: 200
          json:
            $: {{ message: "deleted user with ID of ${{user_id}} successfully" }}
      - id: read-deleted
        request: {{ method: GET, path: "/api/v1/users/${{user_id}}", identity: {who} }}
        expect:
          status: 404
          json:
            $: {{ error: Not found }}

  - id: {p}-006
    name: Renaming one user leaves another unchanged
    setup:
{create(c, 'create-a', 'Ada ${run.id}', 'a_id')}{create(c, 'create-b', 'Bob ${run.id}', 'b_id')}    steps:
      - id: rename-a
        request: {{ method: PUT, path: "/api/v1/users/${{a_id}}", identity: {who}, body: {{ name: "Grace ${{run.id}}" }} }}
        expect:
          status: 200
          present: [$.data]
{stored(c, 'b-unchanged', 'b_id', 'Bob ${run.id}')}
  - id: {p}-007
    name: A list page holds exactly the requested number of users, each with only id and name
    setup:
{create(c, 'create-a', 'Ada ${run.id}')}{create(c, 'create-b', 'Bob ${run.id}')}    steps:
      - id: first-page
        request: {{ method: GET, path: /api/v1/users, identity: {who}, query: {{ limit: "1" }} }}
        expect:
          status: 200
          keys:
            $: [message, data, next_cursor]
            $.data[0]: [id, name]
          length:
            $.data: 1
          json:
            $.message: Fetched users successfully
"""
    if c.get("jwt"):
        s += f"""
  - id: {p}-008
    name: Listing users without a token is refused
    steps:
      - id: list-anonymous
        request: {{ method: GET, path: /api/v1/users, identity: anonymous }}
        expect:
          status: 401
          json:
            $: {{ error: unauthorized }}

  - id: {p}-009
    name: An expired admin token is refused
    steps:
      - id: list-expired
        request: {{ method: GET, path: /api/v1/users, identity: admin, credential: expired }}
        expect:
          status: 401
          json:
            $: {{ error: unauthorized }}

  - id: {p}-010
    name: An anonymous delete is refused and the user still exists
    setup:
{create(c, 'create', 'Ada ${run.id}', 'user_id')}    steps:
      - id: delete-anonymous
        request: {{ method: DELETE, path: "/api/v1/users/${{user_id}}", identity: anonymous }}
        expect:
          status: 401
          json:
            $: {{ error: unauthorized }}
{stored(c, 'still-there', 'user_id', 'Ada ${run.id}')}"""
    return s


def config(c, name):
    s = HEADER + f"version: 1\nproject: {name}\nmanifest: manifest.yaml\nidentities:\n"
    if c.get("jwt"):
        s += "  admin:\n    type: bearer\n    variants: [expired]\n"
    s += "  anonymous: { type: none }\n"
    if c.get("postgres"):
        s += "connections:\n  postgres:\n    app: { schemas: [public], objects: [users] }\n"
    s += "readiness:\n  path: /readyz\n  startup_timeout: 30s\n"
    return s


def binding(c):
    s = f"# Local mode only.\ntarget:\n  base_url: http://127.0.0.1:{c['port']}\n  user_agent: proctor-matrix/0.0\n"
    if c.get("jwt"):
        s += "identities:\n  admin:\n    token_env: PROCTOR_ADMIN_TOKEN\n    variants:\n      expired: { token_env: PROCTOR_ADMIN_EXPIRED_TOKEN }\n"
    if c.get("postgres"):
        s += "connections:\n  postgres:\n    app: { dsn_env: PROCTOR_APP_DB_DSN }\n"
    return s


def write(name, files):
    root = os.path.join(MATRIX, name, "proctor")
    for rel, text in files.items():
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(text)


def main():
    for name, c in REST.items():
        c["who"] = "admin" if c.get("jwt") else "anonymous"
        write(name, {"proctor.yaml": config(c, name),
                     "manifest.yaml": "version: 1\nspecifications:\n  - { id: users, path: specs/users.yaml }\n",
                     "specs/users.yaml": spec(c),
                     "environments/local.yaml": binding(c)})
        print("wrote", name)


if __name__ == "__main__":
    main()
